def race_info(race: str, sub: str | None = None) -> dict:
    """Слить расу и подрасу в один словарь (подраса дополняет и переопределяет)."""
    r = RACES[race]
    out = {k: v for k, v in r.items() if k != "subs"}
    out["traits"] = list(r.get("traits", []))
    out["asi"] = dict(r.get("asi", {}))
    for k in ("langs", "weapons", "armor", "skills", "resist", "tools", "spells"):
        out[k] = list(r.get(k, []))
    if sub and sub in r.get("subs", {}):
        s = r["subs"][sub]
        out["sub_n"] = s["n"]
        for a, v in s.get("asi", {}).items():
            out["asi"][a] = out["asi"].get(a, 0) + v
        for k in ("langs", "weapons", "armor", "skills", "resist", "tools", "spells", "traits"):
            out[k] += s.get(k, [])
        for k in ("spd", "dark", "hp_lvl", "cantrip", "lang_choice", "skill_choice", "feat", "asi_choice", "about"):
            if k in s:
                out[k] = s[k]
    return out
