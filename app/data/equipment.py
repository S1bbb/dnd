def item(name: str, qty: int = 1) -> dict:
    """Предмет инвентаря по названию из справочника (или просто предмет)."""
    it = {"n": name, "qty": qty, "eq": False}
    if name in WEAPONS:
        cat, rng, dmg, dtype, props, _ = WEAPONS[name]
        it.update(kind="weapon", cat=cat, rng=rng, dmg=dmg, dtype=dtype, props=props)
    elif name in ARMOR:
        kind, ac, dexmax, strreq, stealth, _ = ARMOR[name]
        it.update(kind="shield" if kind == "щит" else "armor", akind=kind, ac=ac, dexmax=dexmax, strreq=strreq, stealth=stealth)
    elif name in CONSUMABLES:
        it.update(kind="consumable", desc=CONSUMABLES[name][0], use=CONSUMABLES[name][1])
    elif name in PACKS:
        it.update(kind="pack", desc=PACKS[name])
    else:
        it.update(kind="gear")
    return it


def parse_items(names: list[str]) -> list[dict]:
    """«Ручной топор×2» → предмет с количеством. Одинаковые оружие/доспехи экипируются автоматически позже."""
    out = []
    for raw in names:
        name, _, q = raw.partition("×")
        out.append(item(name.strip(), int(q) if q.isdigit() else 1))
    return out


