ASI_F = ("Увеличение характеристик", "+2 к одной характеристике или +1 к двум (максимум 20), либо черта.", ASI)


def asi_at(*lvls):
    return {lv: [ASI_F] for lv in lvls}


def merge(*ds):
    out = {}
    for d in ds:
        for k, v in d.items():
            out.setdefault(k, []).extend(v)
    return out


