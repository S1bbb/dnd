def class_info(cls: str, sub: str | None = None) -> dict:
    """Класс с учётом подкласса (подкласс может давать магию: мистический рыцарь, ловкач)."""
    c = dict(CLASSES[cls])
    s = c["subs"].get(sub) if sub else None
    if s:
        for k in ("caster", "cast_ab", "prepared", "cantrips", "known"):
            if k in s:
                c[k] = s[k]
    c["sub"] = s
    return c
