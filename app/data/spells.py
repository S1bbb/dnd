DICE_RE = re.compile(r"^\d+(d\d+)?([+-]\d+(d\d+)?|[+-]m)*$|^\d+d\d+\+m$")


def _mech(s: str) -> dict:
    if not s or s == "-":
        return {}
    toks = s.split()
    head = toks[0]
    m = {"kind": head[0]}  # a / s / h / d
    if head.startswith("s:"):
        m["save"] = head[2:]
    for t in toks[1:]:
        if t == "½":
            m["half"] = True
        elif t.startswith("+") and ("d" in t or t[1:].isdigit()):
            m["up"] = t[1:]
        elif re.match(r"^\d", t) and "dice" not in m:
            m["dice"] = t
        else:
            m["type"] = (m.get("type", "") + " " + t).strip()
    return m


def _load() -> dict:
    out = {}
    for line in RAW.strip().splitlines():
        n, lvl, school, cls, time, rng, dur, flags, mech, desc = line.split("|")
        out[n] = {
            "n": n, "lvl": int(lvl), "school": SCHOOLS.get(school, school),
            "cls": [CLASS_CODES[c] for c in cls], "time": TIMES.get(time, time), "rng": rng, "dur": dur,
            "conc": "к" in flags, "ritual": "р" in flags, "m": _mech(mech), "d": desc,
        }
    return out


SPELLS = _load()


def for_class(cls: str, max_lvl: int) -> list[dict]:
    return sorted((s for s in SPELLS.values() if cls in s["cls"] and s["lvl"] <= max_lvl),
                  key=lambda s: (s["lvl"], s["n"]))


def search(text: str, pool=None) -> list[dict]:
    t = text.lower().strip()
    pool = pool if pool is not None else SPELLS.values()
    return [s for s in pool if t in s["n"].lower() or t in s["d"].lower()]
